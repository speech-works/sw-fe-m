import { execFileSync } from "node:child_process";
import { existsSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const projectRoot = join(dirname(fileURLToPath(import.meta.url)), "..");
const assetRoot = join(projectRoot, "app", "assets");
const svgRoot = join(assetRoot, "svg logos");
const logoSource = join(svgRoot, "sw-logo.svg");

// The mark's own orange, measured off the master render. One colour, everywhere:
// a bitmap trace of the logo splits this into several near-identical oranges,
// which is what this pipeline exists to prevent from reaching an asset.
const BRAND = "#F76117";
// palette ink.canvas, the app's own dark. Also app.config.js splash.backgroundColor
// and android.adaptiveIcon.backgroundColor, so the tile never seams against them.
const INK = "#141311";

// The mark's own box inside the 1254 viewBox. Mirrored from sw-logo.svg, which
// centres the mark on (627, 627) using exactly these numbers.
const MARK_W = 436.58;
const MARK_H = 507.64;

// Sizes are declared as the fraction of a 1024 tile's HEIGHT the mark should
// stand, not as raw scale factors, so a logo with different proportions keeps
// its optical weight without anyone re-deriving constants. 0.584 is the
// approved icon size; 0.397 is the splash, deliberately smaller because it sits
// alone on a full screen rather than inside a tile.
const ICON_MARK_FRACTION = 0.584;
const SPLASH_MARK_FRACTION = 0.397;
const scaleFor = (fraction) => +((fraction * 1024) / MARK_H).toFixed(4);

const ICON_SCALE = scaleFor(ICON_MARK_FRACTION);
// A launcher only ever reveals the central 72 of an adaptive layer's 108dp, so
// a foreground drawn at ICON_SCALE would be shown zoomed ~1.5x and clipped.
// Draw it pre-shrunk into exactly that viewport and what the mask reveals
// matches the iOS icon 1:1.
const ADAPTIVE_VIEWPORT = 72 / 108;
const ADAPTIVE_SCALE = ICON_SCALE * ADAPTIVE_VIEWPORT;
const SPLASH_SCALE = scaleFor(SPLASH_MARK_FRACTION);

const source = readFileSync(logoSource, "utf8");
const paths = [...source.matchAll(/<path\b[^>]*\/>/g)].map(([path]) =>
  path.replace(/\sfill="[^"]*"/, ""),
);

if (paths.length !== 1) {
  throw new Error(`Expected one logo contour in sw-logo.svg; found ${paths.length}.`);
}
// Derived rather than hardcoded, so MARK_W/MARK_H and sw-logo.svg cannot drift
// apart silently: if the mark's box changes and these constants don't, this throws.
const expected = `translate(${+(627 - MARK_W / 2).toFixed(2)},${+(627 - MARK_H / 2).toFixed(2)})`;
if (!paths[0].includes(expected)) {
  throw new Error(
    `sw-logo.svg is not centred on (627, 627) for a ${MARK_W} x ${MARK_H} mark ` +
      `(expected ${expected}). Every composition below positions the mark with ` +
      "translate(-627 -627) and would be off-centre.",
  );
}

const geometry = paths.join("");
// Fill is always set on the placing element, never on the geometry, so one
// contour serves every colourway.
const place = (scale, fill) =>
  `<g transform="translate(512 512) scale(${scale}) translate(-627 -627)" fill="${fill}">${geometry}</g>`;

const svg = (body, viewBox = "0 0 1024 1024") =>
  `<?xml version="1.0" encoding="UTF-8"?>\n` +
  `<!-- Generated by scripts/build-logo-assets.mjs from sw-logo.svg. Do not edit. -->\n` +
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${viewBox}">\n  ${body}\n</svg>\n`;

const write = (filename, contents) => writeFileSync(join(svgRoot, filename), contents);

// --- bare mark, one file per colourway -------------------------------------
const markVariants = new Map([
  ["sw-mark.svg", "currentColor"],
  ["sw-mark-white.svg", "#FFFFFF"],
  ["sw-mark-black.svg", "#000000"],
  ["sw-mark-ink.svg", INK],
  ["sw-mark-orange.svg", BRAND],
]);

for (const [filename, fill] of markVariants) {
  write(filename, svg(`<g fill="${fill}">${geometry}</g>`, "0 0 1254 1254"));
}

// --- icon tiles -------------------------------------------------------------
// Flat ink tile, mark on top, nothing else. rx="0" is the store/iOS source:
// both platforms apply their own corner mask and Apple rejects a pre-rounded
// icon. rx="160" is for surfaces that get no mask, i.e. the web favicon.
const tile = (rx, fill) =>
  svg(`<rect width="1024" height="1024" rx="${rx}" fill="${INK}"/>\n  ${place(ICON_SCALE, fill)}`);

write("sw-icon.svg", tile(0, BRAND));
write("sw-icon-white.svg", tile(0, "#FFFFFF"));
write("sw-icon-rounded.svg", tile(160, BRAND));
write("sw-icon-rounded-white.svg", tile(160, "#FFFFFF"));

// --- transparent marks on their own ----------------------------------------
// Splash and the monochrome adaptive layer both sit on a colour the OS paints,
// so the negative space inside the mark has to stay transparent.
write("sw-splash.svg", svg(place(SPLASH_SCALE, "#FFFFFF")));
// The paper mirror. The splash is the flash before any JS runs, so the OS picks
// it from the DEVICE appearance — which means a light-mode user was getting the
// near-black splash and then a cream first screen: exactly the flash of the
// wrong app that the dark splash exists to prevent, inverted. Same mark, same
// scale, ink instead of white, handed to `ios/android.splash.dark`'s light
// counterpart in app.config.js.
write("sw-splash-light.svg", svg(place(SPLASH_SCALE, INK)));
write("sw-adaptive-foreground.svg", svg(place(ADAPTIVE_SCALE, "#FFFFFF")));
// The colour adaptive foreground is full-bleed rather than inset: the ink runs
// to the edge so a circular mask antialiases against the tile, not against
// transparency.
write(
  "sw-adaptive-icon.svg",
  svg(`<rect width="1024" height="1024" fill="${INK}"/>\n  ${place(ADAPTIVE_SCALE, BRAND)}`),
);

// iOS 26 Icon Composer layers, generated as a matching pair so the composed
// icon reads the same as the one that ships. Deliberately flat: Icon Composer
// derives its own specular, blur and shadow for Default/Dark/Clear/Tinted, and
// baking any of that in here would double it. See icon-composer/README.txt.
write(join("icon-composer", "layer-1-background.svg"),
  svg(`<rect width="1024" height="1024" fill="${INK}"/>`));
write(join("icon-composer", "layer-2-foreground.svg"), svg(place(ICON_SCALE, BRAND)));

// --- rasters ----------------------------------------------------------------
const render = (input, output, size, background) => {
  execFileSync("rsvg-convert", [
    "-w",
    String(size),
    "-h",
    String(size),
    ...(background ? ["-b", background] : []),
    join(svgRoot, input),
    "-o",
    output,
  ]);
};

// Store icons must be opaque: App Store Connect rejects an icon with an alpha
// channel, so -b composites the tile onto solid ink and drops transparency.
render("sw-icon.svg", join(assetRoot, "icon.png"), 1024, INK);
render("sw-icon.svg", join(assetRoot, "play-store-icon.png"), 512, INK);

render("sw-adaptive-icon.svg", join(assetRoot, "adaptive-icon.png"), 1024);
render("sw-adaptive-foreground.svg", join(assetRoot, "adaptive-icon-mono.png"), 1024);
render("sw-splash.svg", join(assetRoot, "splash-icon.png"), 1024);
render("sw-splash-light.svg", join(assetRoot, "splash-icon-light.png"), 1024);
render("sw-icon-rounded.svg", join(assetRoot, "favicon.png"), 96);

// --- retired with the previous mark ----------------------------------------
// The old identity shipped as pre-rendered 3D artwork on a wavy texture, which
// no vector source could reproduce. The current mark is drawn, so the tile is
// generated above and these are dead weight. Git still has them.
for (const stale of [
  [svgRoot, "app-logo.png"],
  [svgRoot, "app-logo-original.png"],
  [svgRoot, "sw-icon-flat.svg"],
  [svgRoot, "sw-icon-flat-white.svg"],
  [svgRoot, "sw-mark-amber.svg"],
  // Orphaned warm-gradient wallpaper from the old identity. android.adaptiveIcon
  // sets backgroundColor and no backgroundImage, so nothing has read this since
  // the adaptive foreground became full-bleed.
  [assetRoot, "adaptive-icon-bg.png"],
]) {
  const path = join(stale[0], stale[1]);
  if (existsSync(path)) rmSync(path);
}

// The native splash and launcher images are NOT written here. Expo derives them
// from app/assets/*.png during prebuild, so regenerating the assets above leaves
// ios/ and android/ holding whatever the last prebuild baked in. Skipping this
// step is how a stale mark survives in the splash long after the source is right.
console.log(
  "Logo assets rebuilt.\n" +
    "Native splash + launcher images are baked at prebuild, so run:\n" +
    "  npm run prebuild:ios      && npm run install:ios\n" +
    "  npm run prebuild:android  && npm run install:android",
);
