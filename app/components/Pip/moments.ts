/**
 * Pip's moments: 4 choreography options for each of 24 app moments. The founder plays them and picks 2 per moment.
 *
 * How to read an option:
 * - `beats` is one choreography. `variants` is a set of choreographies under keys:
 *     "1", "2", "3", "4"         a pool: play one each time, never the same one twice in a row
 *     "low", "neutral", "high"   by mood (sad, angry, worried = low; calm, okay = neutral; happy, excited = high)
 *     "level", "stage"           level-up only: an ordinary level, or one of the 4 new stages
 *     "ask", "not-now"           permission-ask only: when the question shows, and after the user taps "Not now"
 * - `ms` is the time until Pip has settled (for `variants`: the longest one). A hand move counts its own time plus 340 ms
 *   when Pip is not on the calm face as it starts. For waiting-empty, `ms` is the length of one loop.
 * - Every option starts from the calm face. The last face stays on; the screen puts Pip back to calm when it moves on.
 * - Every option has a face change on its key beat, so it still reads under reduced motion (faces and haptics only).
 * - peek and rise are entrances: they are only ever the first beat, for a Pip that is just coming onto the screen.
 * - No option shakes the head, looks sad, or marks a wrong answer or a problem with a haptic.
 */
